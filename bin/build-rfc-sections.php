/**
 * Writes the list of sections a memo holds, for the conformance matrix gate to be held against.
 *
 *     php bin/build-rfc-sections.php 6638
 *
 * **Why the list is carried and the memo is not.** `docs/referenzen/README.md` says why the texts are not committed: "sie mitzuliefern hieße, fremde Dokumente zu verteilen", and `download-rfcs.sh` fetches them on demand. A gate that read the text would therefore pass or fail by whether somebody had run that script — which is no gate at all, and on a clean checkout it broke the build.
 *
 * A list of section numbers is not that text. It is a list of identifiers derived from it, the way `Decompositions.php` carries a table derived from UnicodeData.txt, and for the same reason: the data has to be there whether or not the source is.
 *
 * **And it cannot go stale.** A published RFC never changes — RFC 6638 of June 2012 will hold the same 119 sections for ever, and a memo that is revised is a new number. So this runs once per memo the matrix takes on, not on a schedule.
 *
 * @license Apache-2.0
 */

declare(strict_types=1);

require __DIR__ . '/lib/RfcSections.php';

$rfc = $argv[1] ?? '';

if (preg_match('/^\d{3,5}$/', $rfc) !== 1) {
    fwrite(STDERR, "usage: php bin/build-rfc-sections.php <rfc number>\n");

    exit(1);
}

$memo = __DIR__ . '/../docs/referenzen/rfc/rfc' . $rfc . '.txt';
$text = file_get_contents($memo);

if (!is_string($text)) {
    fwrite(STDERR, sprintf(
        "No copy of RFC %s at docs/referenzen/rfc/. Run docs/referenzen/download-rfcs.sh first.\n",
        $rfc,
    ));

    exit(1);
}

$sections = RfcSections::of($text);

if ($sections === []) {
    fwrite(STDERR, sprintf("RFC %s holds no section this can read; the memo may be truncated.\n", $rfc));

    exit(1);
}

$out = __DIR__ . '/../docs/rfc-sections/rfc' . $rfc . '.txt';

@mkdir(dirname($out), 0o777, true);

file_put_contents($out, sprintf(
    "# The sections of RFC %s, one per line, in the order the memo prints them.\n"
    . "#\n"
    . "# Generated by bin/build-rfc-sections.php from docs/referenzen/rfc/rfc%s.txt,\n"
    . "# which is not committed — see docs/referenzen/README.md. A published RFC never\n"
    . "# changes, so this is written once and read by bin/check-rfc-matrix.php.\n"
    . "#\n"
    . "# %d sections.\n%s\n",
    $rfc,
    $rfc,
    count($sections),
    implode("\n", $sections),
));

fwrite(STDOUT, sprintf("  OK   %d sections of RFC %s written to %s\n", count($sections), $rfc, 'docs/rfc-sections/rfc' . $rfc . '.txt'));
