declare(strict_types=1);

namespace DavServices\Plugin;

use Closure;
use DateTimeImmutable;
use DateTimeZone;
use DavServices\Acl\Principal;
use DavServices\CalDav\INotification;
use DavServices\Dav\Event\PropertiesChanging;
use DavServices\Dav\Event\PropertiesRequested;
use DavServices\Dav\ICollection;
use DavServices\Dav\PropFindResult;
use DavServices\Dav\Server;
use DavServices\Uri\Path;
use DavServices\Xml\Element;

/**
 * The notification mechanism (R-CAL-21).
 *
 *     $notifications = new Notifications($server);
 *     $notifications = new Notifications($server, at: 'alerts');
 *
 *     $notifications->register();
 *
 * ## There is no RFC, and the source was fetched rather than remembered
 *
 * `caldav-sharing`, "Shared and Published Calendars in CalDAV", C. Daboo and
 * E. York, Apple, 19 September 2012 — a Calendar Server extension that never
 * became an IETF document. `docs/referenzen/download-extensions.sh` fetches
 * it, and every decision here is one of §4's sentences.
 *
 * **It is a generic mechanism**, §4 saying so itself: "this specification
 * defines a new generic notification mechanism for CalDAV servers". The
 * sharing it was written for (R-CAL-20) is the first thing to deposit into
 * it, and §5.3.2's "the server MUST send a notification message to any sharees
 * whose status is changed" is why this comes first: sharing without somewhere
 * to put an invitation could not meet a MUST of its own section.
 *
 * ## It owes two properties
 *
 * - **`CS:notification-URL`** (§4.1.1) on a principal, holding a `DAV:href` to
 *   that principal's notification collection — "Identify the URL of the
 *   notification collection owned by the associated principal resource."
 * - **`CS:notificationtype`** (§4.2.1) on each notification, holding the one
 *   element that says what kind it is.
 *
 * Both are withheld from `allprop`, both sections asking for that in the same
 * words, and both are protected — §4.1.1 with a SHOULD and §4.2.1 with a
 * MUST.
 *
 * ## The URL is the tree's answer, not a pattern's
 *
 * §4.1.1's description ends: "If not present, then the associated calendar
 * user is not enabled for notification messages on the server." So the
 * property is answered only where the collection is really there. A server
 * that built the URL from the principal's name regardless would hand every
 * client a path to poll and §4's "Clients SHOULD monitor the notification
 * collection" would have them poll a `404` for ever.
 *
 * Where the collections live is the deployment's layout, which is why it is a
 * constructor argument — the same reason {@see CalDav} takes the path its
 * calendar homes are under.
 *
 * ## What is not here yet
 *
 * **Nothing deposits a notification.** §4 has them "automatically generated by
 * the server", and the first server action that generates one is a share
 * (§5.3.2, R-CAL-20). The seam for writing one belongs with the thing that
 * needs it rather than ahead of it — a seam built on speculation is a seam
 * built to the wrong shape.
 *
 * **No `calendarserver-sharing` token.** §5.1 asks a server that supports "the
 * features described in this document" to announce it, and that document
 * describes §4's notifications *and* §5's sharing. Announcing it with only the
 * first would have a client offer sharing and then be told the method is not
 * allowed, which is worse than silence: §5.1 is how a client decides whether
 * to offer it at all.
 *
 * **Two of §4's MAYs are not taken.** "Servers MAY delete notification
 * resources on their own if they determine that the notifications are no
 * longer relevant or valid" and "Servers MAY coalesce notifications as
 * appropriate" — both are judgements about somebody's data that a library has
 * no grounds to make. A store that wants either does it itself.
 */
final class Notifications
{
    /**
     * §4.1.1's property, which says where a principal's notifications are.
     */
    public const NOTIFICATION_URL = '{http://calendarserver.org/ns/}notification-URL';

    /**
     * §4.2.1's property, which says what kind one notification is.
     */
    public const NOTIFICATION_TYPE = '{http://calendarserver.org/ns/}notificationtype';

    private const HREF = '{DAV:}href';

    private const CANNOT_MODIFY_PROTECTED = '{DAV:}cannot-modify-protected-property';

    /**
     * §6.24's root element of a notification resource.
     *
     * **The same name as the resource type** in
     * {@see \DavServices\CalDav\NotificationCollection::NOTIFICATION}, and
     * the document means two different things by it: there, which kind of
     * collection this is; here, the root of a message inside it. Written out
     * again rather than borrowed, because the two have nothing to do with
     * each other beyond the spelling.
     */
    private const NOTIFICATION = '{http://calendarserver.org/ns/}notification';

    private const DTSTAMP = '{http://calendarserver.org/ns/}dtstamp';

    /**
     * How §6.25's stamp is written.
     *
     * **The document does not say**, and the nearest thing that does is RFC
     * 4918 §15.1, which gives `DAV:creationdate` the value "date-time
     * (defined in [RFC3339])" — a date inside a WebDAV XML element, which is
     * exactly what this is. The `Z` is RFC 3339's own spelling for UTC, and
     * the moment is converted into it so that two servers' stamps can be
     * compared at all.
     */
    private const WHEN = 'Y-m-d\TH:i:s\Z';

    /** @var Closure(): DateTimeImmutable */
    private readonly Closure $now;

    /**
     * @param string $at The collection the per-principal notification
     *                   collections hang under, as a path inside this tree. A
     *                   principal with nothing there is one §4.1.1 calls "not
     *                   enabled for notification messages"
     * @param callable(): DateTimeImmutable|null $now What the clock says, for
     *                                                §6.25's stamp
     */
    public function __construct(
        private readonly Server $server,
        private readonly string $at = 'notifications',
        ?callable $now = null,
    ) {
        $this->now = $now === null
            ? static fn (): DateTimeImmutable => new DateTimeImmutable()
            : $now(...);
    }

    /**
     * Leaves a notification where this principal will find it.
     *
     * **This is the seam P7-06 would not build**, and it is built now because
     * something needs it: §5.3.2 makes a notification part of every sharing
     * change, and {@see Sharing} is what deposits one. §4 has the messages
     * "automatically generated by the server", which is what this is.
     *
     * The message is wrapped as §6.24 requires — `<!ELEMENT notification
     * (CS:dtstamp, (invite-notification | invite-reply)>` — so a caller hands
     * over the type element alone and this adds the stamp §6.25 asks for.
     * That rule lives here rather than in every caller because it is §4's
     * rule rather than sharing's.
     *
     * **A second message about one thing replaces the first.** §4 makes
     * deleting a notification "no longer relevant or valid" a server's MAY,
     * and this takes that MAY as narrowly as it can be taken: not by judging
     * somebody's data, but because the server that wrote the old message has
     * just made it untrue. The resource keeps its URL, so a client watching
     * the collection sees it change rather than losing one and gaining
     * another.
     *
     * @param string $uid What the message is about, which §6.16 makes an
     *                    identifier of the server's own choosing — it becomes
     *                    the resource's name, so it has to be usable as one
     *
     * @return bool Whether there was anywhere to put it. False is §4.1.1's
     *              principal who is "not enabled for notification messages",
     *              and it is not a failure: §5.3.2's MUST reaches no further
     *              than the mechanism §4 provides
     */
    public function deposit(Principal $principal, string $uid, Element $type): bool
    {
        $path = Path::join($this->at, $principal->name());

        if (!$this->server->tree()->exists($path)) {
            return false;
        }

        $collection = $this->server->tree()->node($path);

        if (!$collection instanceof ICollection) {
            return false;
        }

        $name = $uid . '.xml';

        if ($collection->hasChild($name)) {
            $collection->child($name)->delete();
        }

        $collection->createFile($name, $this->server->writer()->write($this->messageAbout($type)));
        $this->server->tree()->forget($path);

        return true;
    }

    /**
     * Switches the two properties on.
     *
     * **No `Report` and no method**, unlike the other plugins: §4 adds no
     * report, and a notification is read with a `GET` and deleted with a
     * `DELETE` like any other resource. That is the mechanism's whole charm —
     * a client that can read a collection can read its notifications.
     */
    public function register(): void
    {
        $events = $this->server->events();

        $events->on(PropertiesRequested::class, $this->describe(...));
        $events->on(PropertiesChanging::class, $this->guardChangingProperties(...));
    }

    /**
     * Answers whichever of the two was asked for by name.
     */
    private function describe(PropertiesRequested $event): void
    {
        $node = $event->node();
        $result = $event->result();

        if ($node instanceof Principal) {
            $this->nameTheCollection($result, $node);
        }

        if ($node instanceof INotification) {
            $this->nameTheType($result, $node);
        }
    }

    /**
     * §4.1.1, where the principal has a notification collection.
     *
     * **Asked for by name only**, that section's PROPFIND behaviour being
     * "This property SHOULD NOT be returned by a PROPFIND allprop request" —
     * the same sentence {@see PropFindResult::wasNamed()} exists for.
     *
     * The collection is named with its trailing slash, which RFC 4918 §5.2
     * asks for wherever a server produces the URL of a collection.
     */
    private function nameTheCollection(PropFindResult $result, Principal $node): void
    {
        if (!$result->wasNamed(self::NOTIFICATION_URL)) {
            return;
        }

        $path = Path::join($this->at, $node->name());

        // §4.1.1: "If not present, then the associated calendar user is not
        // enabled for notification messages on the server." The tree is what
        // knows, so the tree is asked — and it is asked here rather than in
        // `register()` because a deployment may make the collection at any
        // time, and a plugin that decided once would answer yesterday's tree.
        if (!$this->server->tree()->exists($path)) {
            return;
        }

        $url = new Element(self::NOTIFICATION_URL);
        $href = new Element(self::HREF);

        $href->appendText($this->server->href($path) . '/');
        $url->append($href);

        $result->set(self::NOTIFICATION_URL, $url);
    }

    /**
     * §4.2.1, the kind of one notification.
     *
     * **One sentence, two rules pulling against each other:** "The single
     * child element is the notification resource root element's child defining
     * the notification itself. This element MUST be empty, though any
     * attributes on the element in the notification resource MUST be present
     * in the property element."
     *
     * So the element is rebuilt from its name and its attributes, which is
     * what makes it empty and keeps them in one step. Copying the element and
     * removing its children would be the same thing said twice, and the second
     * saying is where a child would survive.
     *
     * Asked for by name only, for the reason §4.2.1 gives in the same words as
     * §4.1.1.
     */
    private function nameTheType(PropFindResult $result, INotification $node): void
    {
        if (!$result->wasNamed(self::NOTIFICATION_TYPE)) {
            return;
        }

        $kind = $node->notificationType();
        $property = new Element(self::NOTIFICATION_TYPE);

        $property->append(new Element($kind->name(), $kind->attributes()));

        $result->set(self::NOTIFICATION_TYPE, $property);
    }

    /**
     * §6.24's document, around whatever kind of message this is.
     */
    private function messageAbout(Element $type): Element
    {
        $notification = new Element(self::NOTIFICATION);
        $stamp = new Element(self::DTSTAMP);

        $stamp->appendText(($this->now)()->setTimezone(new DateTimeZone('UTC'))->format(self::WHEN));
        $notification->append($stamp);
        $notification->append($type);

        return $notification;
    }

    /**
     * §4.1.1's "SHOULD be protected" and §4.2.1's "MUST be protected".
     *
     * **Both for the same reason: the server works them out.** Where a
     * notification collection is, is the deployment's layout, and what kind a
     * notification is, is what the server wrote into it. A client that could
     * change the kind could make a notification it cannot handle look like one
     * it can, and then act on it.
     *
     * **Nothing else is touched.** A notification collection is somewhere a
     * client keeps a `DAV:displayname`, and a plugin that refused every write
     * because two names are protected would be found by the first deployment
     * that set one.
     */
    private function guardChangingProperties(PropertiesChanging $event): void
    {
        $result = $event->result();

        foreach (array_keys($result->mutations()) as $name) {
            if ($name === self::NOTIFICATION_URL || $name === self::NOTIFICATION_TYPE) {
                $result->set($name, 403, self::CANNOT_MODIFY_PROTECTED);
            }
        }
    }
}
