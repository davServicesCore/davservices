declare(strict_types=1);

namespace DavServices\CalDav;

use DateTimeImmutable;
use DavServices\Dav\ICollection;
use DavServices\Dav\INode;
use DavServices\Dav\IProperties;
use DavServices\Dav\IResourceType;

/**
 * The collection a user's notification messages are deposited into (R-CAL-21).
 *
 *     $home->add(NotificationCollection::of($yourCollection));
 *
 * ## There is no RFC, and the source was fetched rather than remembered
 *
 * `caldav-sharing`, "Shared and Published Calendars in CalDAV", C. Daboo and
 * E. York, Apple, 19 September 2012 — the same Calendar Server extension
 * document whose §5 defines sharing, fetched by
 * `docs/referenzen/download-extensions.sh`. §4 of it defines this mechanism,
 * and one sentence defines this class:
 *
 * > The notification collection referenced by the CS:notification-URL property
 * > MUST have a DAV:resourcetype property with DAV:collection and
 * > CS:notification child elements.
 *
 * ## Why it comes before the sharing it was written for
 *
 * §4 calls it "a new **generic** notification mechanism for CalDAV servers",
 * so it is a thing in its own right rather than a seam built on speculation.
 * And sharing needs it: §5.3.2 has the server "MUST send a notification
 * message to any sharees whose status is changed", so a sharing protocol
 * without this collection could not meet a MUST of its own section — a sharee
 * would never learn of the invitation, which §3 gives as the whole flow.
 *
 * ## What is in it, and who puts it there
 *
 * > Notifications are automatically generated by the server (perhaps in
 * > response to a client action) with an appropriate resource stored in the
 * > notifications collection of the user to whom the notification is targeted.
 *
 * So a client never creates one. It reads them, looks at
 * `CS:notificationtype` to find the ones it can handle, and deletes what it
 * has dealt with — "it SHOULD delete the notification resource". A write
 * therefore goes **through** rather than being refused here: the server is the
 * one writing, and this wrapper has no way to tell the server's write from
 * anyone else's. Whether a *client* may write is a question about access, and
 * {@see \DavServices\Plugin\Acl} answers it where it answers every other
 * write.
 *
 * ## It wraps rather than replaces
 *
 * Where the notifications are kept is the application's business, exactly as
 * for {@see Subscription}, and {@see of()} is the only way in for the reason
 * that class gives: `IProperties` is a claim, not a convenience, and a wrapper
 * that made it over a store keeping no properties would silently take dead
 * property storage away.
 *
 * **The library deposits nothing yet**, because nothing generates a
 * notification until the sharing protocol does (R-CAL-20). A seam for that
 * belongs with the thing that needs it rather than ahead of it.
 */
class NotificationCollection implements ICollection, IResourceType
{
    /**
     * What makes a collection a notification collection, beside
     * `DAV:collection` — which the server adds for every collection by itself.
     */
    public const NOTIFICATION = '{http://calendarserver.org/ns/}notification';

    /**
     * Protected on purpose: {@see of()} is the only way in, because it is the
     * one place that can choose correctly between this class and the one that
     * also keeps properties.
     */
    protected function __construct(private readonly ICollection $collection)
    {
    }

    /**
     * A notification collection over this collection.
     *
     * **It hands back something that keeps properties only where there is a
     * store behind it that does**, which is {@see Subscription::of()}'s reason
     * in full: {@see \DavServices\Plugin\DeadProperties} steps aside for any
     * node implementing `IProperties`, so a claim made over a store that keeps
     * none takes dead property storage away without saying so.
     */
    public static function of(ICollection $collection): self
    {
        if ($collection instanceof IProperties) {
            return new NotificationCollectionKeepingItsOwn($collection);
        }

        return new self($collection);
    }

    /**
     * The collection the notifications are really in.
     *
     * Read by a plugin that was handed a node and needs the store behind it,
     * so that it does not have to unwrap one by hand.
     */
    public function collection(): ICollection
    {
        return $this->collection;
    }

    /**
     * A notification collection, and whatever else it already was.
     *
     * A resource type is a list rather than a label (RFC 4918 §15.9), so a
     * collection that is both this and something an application invented says
     * both.
     *
     * @return list<string>
     */
    public function resourceTypes(): array
    {
        if (!$this->collection instanceof IResourceType) {
            return [self::NOTIFICATION];
        }

        return [self::NOTIFICATION, ...$this->collection->resourceTypes()];
    }

    /**
     * The name the store gave it, which is the last segment of its URL.
     */
    public function name(): string
    {
        return $this->collection->name();
    }

    /**
     * When the store last saw it change, or null where it does not keep that.
     */
    public function lastModified(): ?DateTimeImmutable
    {
        return $this->collection->lastModified();
    }

    /**
     * Removes the collection; being a notification collection adds no reason
     * to keep it.
     *
     * A principal with no notification collection is one §4.1.1 describes
     * exactly: "If not present, then the associated calendar user is not
     * enabled for notification messages on the server."
     */
    public function delete(): void
    {
        $this->collection->delete();
    }

    /**
     * The notifications the store holds.
     *
     * @return list<INode>
     */
    public function children(): array
    {
        return $this->collection->children();
    }

    /**
     * One notification by name, as the store raised it: a member that is not
     * there is the store's `NotFound` rather than something made up here.
     */
    public function child(string $name): INode
    {
        return $this->collection->child($name);
    }

    /**
     * Whether the store holds a notification of that name.
     */
    public function hasChild(string $name): bool
    {
        return $this->collection->hasChild($name);
    }

    /**
     * Puts a notification in, and hands back whatever the store tagged it
     * with.
     *
     * **The server is the one that writes here** (§4: "Notifications are
     * automatically generated by the server"), so a wrapper that refused
     * would make the mechanism impossible to build. The tag is passed on
     * rather than swallowed: without it every write looks untagged and sends a
     * client into a `GET` it did not need.
     */
    public function createFile(string $name, mixed $content = null): ?string
    {
        return $this->collection->createFile($name, $content);
    }

    /**
     * Makes a plain collection inside it, if the store will.
     *
     * Nothing in §4 provides for one and nothing forbids one, so this is the
     * store's decision — a wrapper that refused would be stricter than
     * anything it could cite.
     */
    public function createCollection(string $name): void
    {
        $this->collection->createCollection($name);
    }
}
